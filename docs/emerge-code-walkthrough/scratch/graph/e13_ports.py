import json, pickle
from fx import try_
from emerge.graph import Port, Ref, Message, MainAgentMessage
from emerge.graph.ports import freeze, thaw, FrozenDict, FrozenList
print("== Port")
try_("Port ok", lambda: Port(name="rgb", type_tag="image/rgb"))
try_("Port name with dot", lambda: Port(name="a.b", type_tag="x"))
try_("Port empty type_tag", lambda: Port(name="a", type_tag=""))
try_("Port extra", lambda: Port(name="a", type_tag="x", foo=1))
print("== Ref")
R = lambda **kw: Ref(**{"producer": "cam", "producer_instance": "cam@v0", "port": "rgb", "key": "f1", **kw})
for k in ["", ".", "..", "a/b", "a\\b", "a..b", ".hidden", "a b", "帧1"]:
    try_(f"key {k!r}", lambda k=k: R(key=k).key)
try_("producer with dot", lambda: R(producer="a.b"))
try_("producer_instance ''", lambda: R(producer_instance=""))
try_("producer_instance 'cam@v0' allowed (no pattern)", lambda: R(producer_instance="x y.z").producer_instance)
try_("port with space", lambda: R(port="a b"))
print("same key diff port equal?", R() == R(port="depth"), "| diff instance equal?", R() == R(producer_instance="cam@v1"))
print("== Message")
base = dict(source_node="cam", source_instance="cam@v0", source_port="rgb", version=0, timestamp=1.0, content_time=0)
try_("Message minimal", lambda: Message(**base))
try_("version -1", lambda: Message(**{**base, "version": -1}))
try_("content_time -1", lambda: Message(**{**base, "content_time": -1}))
try_("content_time missing", lambda: Message(**{k: v for k, v in base.items() if k != "content_time"}))
try_("source_instance ''", lambda: Message(**{**base, "source_instance": ""}))
try_("source_node with dot (no pattern)", lambda: Message(**{**base, "source_node": "a.b"}).source_node)
try_("data list", lambda: Message(**base, data=[1, 2]))
m = Message(**base, data={"a": [1, {"b": 2}], "t": (1, 2)}, refs=[{"producer": "cam", "producer_instance": "cam@v0", "port": "rgb", "key": "k"}])
print("data type:", type(m.data).__name__, type(m.data["a"]).__name__, type(m.data["t"]).__name__, "| refs:", type(m.refs[0]).__name__)
try_("mutate data", lambda: m.data.__setitem__("x", 1))
try_("mutate nested list", lambda: m.data["a"].append(3))
try_("data |= ", lambda: m.data.__ior__({"x": 1}))
print("data == plain dict:", m.data == {"a": [1, {"b": 2}], "t": [1, 2]}, "| json.dumps:", json.dumps(m.data))
print("pickle roundtrip type:", type(pickle.loads(pickle.dumps(m.data))).__name__, "| model_dump data type:", type(m.model_dump()["data"]).__name__)
c = m.data.copy(); c["x"] = 1
print("copy() type:", type(c).__name__, "| m.data | {} type:", type(m.data | {}).__name__)
print("thaw:", type(thaw(m.data)).__name__, "| freeze of tuple ->", type(freeze((1, 2))).__name__)
print("== MainAgentMessage")
try_("seq 0", lambda: MainAgentMessage(seq=0, timestamp=1.0, content_time=0))
try_("seq 1", lambda: MainAgentMessage(seq=1, timestamp=1.0, content_time=3, text="hi"))
try_("no content_time", lambda: MainAgentMessage(seq=1, timestamp=1.0))
