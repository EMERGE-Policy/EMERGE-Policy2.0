from emerge.graph import Graph, NodeSpec, StartEdge, StartSource, start_status
def S(n, o=None): return StartSource(node=n, outcome=o)
def E(*s): return StartEdge(sources=tuple(s))
def N(i, *edges): return NodeSpec(id=i, type="t", start_edges=tuple(edges))
def show(label, g, ended):
    r = start_status(g, ended)
    print(f"{label:70s} -> " + ", ".join(f"{k}={v.value}" for k, v in r.items()))

g = Graph(nodes=(N("a"), N("b", E(S("a")))))
show("root a, nothing ended", g, {})
show("a ended 'success' (b: a done)", g, {"a": "success"})
show("a ended None (b: a done)", g, {"a": None})
g = Graph(nodes=(N("a"), N("b", E(S("a", "success")))))
show("b: a[success]; a ended 'failure'", g, {"a": "failure"})
show("b: a[success]; a ended 'success'", g, {"a": "success"})
show("b: a[success]; a ended None", g, {"a": None})
g = Graph(nodes=(N("a"), N("c"), N("b", E(S("a", "success"), S("c")))))
show("b: a[success] and c; only a ended success", g, {"a": "success"})
show("b: a[success] and c; a success, c None", g, {"a": "success", "c": None})
show("b: a[success] and c; both done", g, {"a": "success", "c": "x"})
g = Graph(nodes=(N("v"), N("p", E(S("v", "success"))), N("r", E(S("v", "failure"))), N("q", E(S("r"))), N("x", E(S("p")), E(S("r")))))
show("V success -> P; V failure -> R; R->Q; P or R -> X ; V=success", g, {"v": "success"})
show("same, V=failure", g, {"v": "failure"})
show("same, V=None (stopped/failed)", g, {"v": None})
show("same, V=success, P ended 'ok'", g, {"v": "success", "p": "ok"})
g = Graph(nodes=(N("b", E(S("ghost"))),))
show("source not in graph", g, {})
show("source not in graph but listed in ended", g, {"ghost": "ok"})
g = Graph(nodes=(N("b", E()),))
show("only an empty edge", g, {})
g = Graph(nodes=(N("a"), N("b", E(), E(S("a")))))
show("empty edge + a; a running", g, {})
g = Graph(nodes=(N("a", E(S("b"))), N("b", E(S("a"))), N("c", E(S("a")))))
show("cycle a<->b, c behind", g, {})
g = Graph(nodes=(N("a"), N("b", E(S("a"))), N("c", E(S("b")))))
show("chain a->b->c, a ended None (propagation)", g, {"a": None})
show("chain a->b->c, b listed as skipped(None)", g, {"a": None, "b": None})
show("ended contains ids not in graph", g, {"zzz": "ok"})
g = Graph(nodes=(N("a"), N("a", E(S("zz")))))
show("duplicate id a (first is root)", g, {})
g = Graph(nodes=(N("a"), N("b", E(S("a"), S("a", "success")))))
show("same source twice on edge: a and a[success]; a ended 'x'", g, {"a": "x"})
