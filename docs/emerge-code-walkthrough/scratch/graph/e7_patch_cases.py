import logging, textwrap
from pathlib import Path
from fx import REG, try_
from emerge.graph import (GraphBuilder, GraphPatch, Edit, apply_graph_patch, diff_graphs, StartEdge, StartSource,
                          start_status, NodeRegistry, set_active_registry)
logging.basicConfig(level=logging.WARNING, format="LOG %(name)s: %(message)s")

def base():
    b = GraphBuilder(REG)
    b.add_node("a", "src").add_node("t", "mid", after=["a"]).add_node("c", "sink", after=["t"])
    b.connect_ports("a.out", "t.inp").connect_ports("t.out", "c.inp")
    return b.build()
g0 = base()
A = lambda p, **kw: apply_graph_patch(g0, p, REG, **kw)

print("== empty patch")
print("same object:", A(GraphPatch()) is g0)
print("== same-patch rules")
try_("remove then add same id", lambda: A(GraphPatch.remove_node("c").combine_patches(GraphPatch.add_node("c", "sink", after=["t"]))))
try_("add existing id", lambda: A(GraphPatch.add_node("a", "src")))
try_("add then replace same id", lambda: A(GraphPatch.add_node("x", "src").combine_patches(GraphPatch.replace_node("x"))))
try_("replace twice", lambda: A(GraphPatch.replace_node("t").combine_patches(GraphPatch.replace_node("t"))))
try_("replace then remove", lambda: A(GraphPatch.replace_node("c").combine_patches(GraphPatch.remove_node("c"))))
try_("remove then replace", lambda: A(GraphPatch.remove_node("c").combine_patches(GraphPatch.replace_node("c"))))
try_("remove twice", lambda: A(GraphPatch.remove_node("c").combine_patches(GraphPatch.remove_node("c"))))
try_("update_params twice on running", lambda: A(GraphPatch.replace_node_params("t", {"k": 2}).combine_patches(GraphPatch.replace_node_params("t", {"k": 3})), states={"t": "running"}))
try_("update_params twice on pending (last wins)", lambda: A(GraphPatch.replace_node_params("t", {"k": 2}).combine_patches(GraphPatch.replace_node_params("t", {"k": 3}))).node("t").params)
try_("update_params on running + replace_node", lambda: A(GraphPatch.replace_node_params("t", {"k": 2}).combine_patches(GraphPatch.replace_node("t")), states={"t": "running"}))
try_("update_params(None) on pending", lambda: A(GraphPatch(edits=(Edit(op="update_params", node="t"),))).node("t").params)
try_("op on missing node", lambda: A(GraphPatch.set_node_description("zz", "x")))
try_("Edit add_node without node", lambda: A(GraphPatch(edits=(Edit(op="add_node", type="src"),))))
try_("Edit add_node without type", lambda: A(GraphPatch(edits=(Edit(op="add_node", node="q"),))))
try_("connect without target", lambda: A(GraphPatch(edits=(Edit(op="connect", source="a.out"),))))
try_("connect bad endpoint", lambda: A(GraphPatch.connect("aout", "t.inp")))
try_("disconnect nonexistent", lambda: A(GraphPatch.disconnect("a.aux", "t.inp")))
try_("unknown op", lambda: Edit(op="set_after", node="t"))
print("== remove_node and start edges")
try_("remove t (pending) leaving c's edge", lambda: A(GraphPatch.remove_node("t")))
try_("remove t, c running", lambda: A(GraphPatch.remove_node("t"), states={"c": "running"}))
try_("remove t, c skipped", lambda: A(GraphPatch.remove_node("t"), states={"c": "skipped"}))
try_("remove t + fix c edges", lambda: str(A(GraphPatch.remove_node("t").combine_patches(GraphPatch.replace_start_edges("c")))))
try_("remove t + remove c", lambda: str(A(GraphPatch.remove_node("t").combine_patches(GraphPatch.remove_node("c")))))
try_("remove a (t running has edge on a)", lambda: A(GraphPatch.remove_node("a"), states={"t": "running"}))
try_("remove t whose input source a is finished (subs into ended?)", lambda: str(A(GraphPatch.remove_node("t").combine_patches(GraphPatch.replace_start_edges("c")), states={"a": "finished"})))
try_("remove c (pending) whose source t is finished", lambda: str(A(GraphPatch.remove_node("c"), states={"t": "finished"})))
print("== rewire order")
try_("connect new then disconnect old", lambda: str(diff_graphs(g0, A(GraphPatch.connect("a.aux", "t.inp").combine_patches(GraphPatch.disconnect("a.out", "t.inp")))).subscriptions))
try_("connect second source only", lambda: A(GraphPatch.connect("a.aux", "t.inp")))
print("== validation errors after edits")
try_("add node of unknown type + bad params", lambda: A(GraphPatch.add_node("q", "nope").combine_patches(GraphPatch.replace_node_params("t", {"k": "x"}))))
try_("add node with start edge on unknown outcome", lambda: A(GraphPatch.add_node("q", "sink", start_edges=(StartEdge(sources=(StartSource(node="a", outcome="done"),)),))))
print("== replace semantics")
g1 = A(GraphPatch.replace_node("t"), states={"t": "running"})
n0, n1 = g0.node("t"), g1.node("t")
print("instance", n0.instance_id, "->", n1.instance_id, "| start edges kept:", n0.start_edges == n1.start_edges, "| desc kept:", n0.description == n1.description, "| params kept:", n0.params == n1.params, "| subs same:", g0.subscriptions == g1.subscriptions)
print("record:", g1.replacements)
g2 = apply_graph_patch(g1, GraphPatch.replace_node("t", params={}), REG)
print("after 2nd replace: instance", g2.node("t").instance_id, "params", dict(g2.node("t").params), "| replacements_of:", [(r.old_instance_id, r.new_instance_id, r.version) for r in g2.replacements_of("t")])
d = diff_graphs(g0, g2)
print("diff v0->v2 replaced (synthesized):", d.nodes.replaced)
g3 = apply_graph_patch(g2, GraphPatch.remove_node("c"), REG)
g4 = apply_graph_patch(g3, GraphPatch.add_node("c", "sink", after=["t"]).combine_patches(GraphPatch.connect("t.out", "c.inp")), REG)
d = diff_graphs(g2, g4)
print("remove then re-add across patches: c", g2.node("c").instance_id, "->", g4.node("c").instance_id, "| diff:", d.nodes.replaced, "| history for c:", g4.replacements_of("c"))
print("is_current old:", g4.is_current("t", "t@v0"), "new:", g4.is_current("t", "t@v2"))
print("== port compatibility on replace")
try_("t: mid -> mid2 (out tag img->mask, c.inp expects img)", lambda: A(GraphPatch.replace_node("t", "mid2", params={})))
try_("t: mid -> mid2 + rewire c to a.out", lambda: str(A(GraphPatch.replace_node("t", "mid2", params={}).combine_patches(GraphPatch.disconnect("t.out", "c.inp"), GraphPatch.connect("a.out", "c.inp")))))
try_("t: mid -> mid3 (no out port)", lambda: A(GraphPatch.replace_node("t", "mid3", params={})))
try_("t: mid -> mid2 keeping params {'k':1}", lambda: A(GraphPatch.replace_node("t", "mid2")))
# pre-existing mismatch
b = GraphBuilder(REG); b.add_node("m", "mid2").add_node("s", "sink").connect_ports("m.out", "s.inp")
gm = b.build()
try_("pre-existing mismatch, replace m with same type", lambda: str(apply_graph_patch(gm, GraphPatch.replace_node("m"), REG).version))
try_("update_params running t -> new instance keeps code", lambda: A(GraphPatch.replace_node_params("t", {"k": 9}), states={"t": "paused"}).replacements[-1])

print("== generated code pinning")
GEN = Path(__file__).resolve().parent / "gen"; GEN.mkdir(exist_ok=True)
r = NodeRegistry(); prev = set_active_registry(r)
r.register(type(REG.find_entry("src").cls).__call__ and REG.find_entry("src").cls, REG.find_entry("src").locator)
f1 = GEN / "cam_v1.py"; f1.write_text(textwrap.dedent('''
    from emerge.graph import Node, Port
    class Cam(Node):
        name = "cam"; outcomes = ("ok",); outputs = (Port(name="out", type_tag="img"),)
'''))
f2 = GEN / "cam_v2.py"; f2.write_text(textwrap.dedent('''
    from emerge.graph import Node, Port
    class Cam(Node):
        name = "cam"; outcomes = ("ok", "bad"); outputs = (Port(name="out", type_tag="img"),)
'''))
r.register_from_file(f1, "1")
gg = GraphBuilder(r).add_node("k", "cam").add_node("k2", "cam", code="9").build_unvalidated_graph()
print("builder pins: k ->", gg.node("k").code, "| k2 explicit ->", gg.node("k2").code)
from emerge.graph import validate
print("validate k2@9:", [i.code.value for i in validate(gg, r).issues])
gk = GraphBuilder(r).add_node("k", "cam").build()
r.register_from_file(f2, "2")
print("catalog now cam@", r.pin("cam"))
print("replace_node(k) code omitted ->", apply_graph_patch(gk, GraphPatch.replace_node("k"), r).node("k").code)
print("replace_node(k, code='1') ->", apply_graph_patch(gk, GraphPatch.replace_node("k", code="1"), r).node("k").code)
print("update_params(k) on running ->", try_("", lambda: apply_graph_patch(gk, GraphPatch.replace_node_params("k", {}), r, states={"k": "running"}).node("k").code))
print("add_node cam ->", apply_graph_patch(gk, GraphPatch.add_node("k3", "cam"), r).node("k3").code)
try_("start edge k[bad] on k pinned to v1 (bad only in v2)", lambda: apply_graph_patch(gk, GraphPatch.add_node("z", "src", start_edges=(StartEdge(sources=(StartSource(node="k", outcome="bad"),)),)), r))
set_active_registry(prev)

print("== states edge cases")
try_("states has unknown id", lambda: A(GraphPatch.set_node_description("t", "x"), states={"zzz": "running"}).version)
try_("weird state string -> remove", lambda: A(GraphPatch.remove_node("c"), states={"c": "weird"}))
try_("weird state string -> update_params", lambda: A(GraphPatch.replace_node_params("t", {"k": 2}), states={"t": "weird"}))
print("== no-op edits")
g_same = A(GraphPatch.set_node_description("t", g0.node("t").description))
print("same description: version", g_same.version, "diff:", bool(diff_graphs(g0, g_same)))
print("== new start edge on ended node (judged by caller)")
gx = A(GraphPatch.add_node("x", "sink", start_edges=(StartEdge(sources=(StartSource(node="a", outcome="failure"),)),)).combine_patches(GraphPatch.connect("a.out", "x.inp")), states={"a": "finished", "t": "running"})
print("x after a(finished: success):", start_status(gx, {"a": "success"}).get("x"), "| after a(finished: failure):", start_status(gx, {"a": "failure"}).get("x"))
