from fx import try_
from emerge.graph import (Graph, NodeSpec, StartEdge, StartSource, Subscription, start_status, StartStatus,
                          start_edges_from_after, parse_endpoint, make_instance_id)

def S(n, o=None): return StartSource(node=n, outcome=o)
def E(*srcs): return StartEdge(sources=tuple(srcs))
def N(i, t="src", *edges, **kw): return NodeSpec(id=i, type=t, start_edges=tuple(edges), **kw)
def sub(a, b):
    an, ap = a.split("."); bn, bp = b.split(".")
    return Subscription(source_node=an, source_port=ap, target_node=bn, target_port=bp)

print("== edge helpers")
try_("parse 'a.b'", lambda: parse_endpoint("a.b"))
try_("parse 'a.b.c'", lambda: parse_endpoint("a.b.c"))
try_("parse 'ab'", lambda: parse_endpoint("ab"))
try_("parse '.b'", lambda: parse_endpoint(".b"))
try_("parse 'a.'", lambda: parse_endpoint("a."))
try_("parse 'a b.c'", lambda: parse_endpoint("a b.c"))
try_("after ['a','b','a']", lambda: [str(e) for e in start_edges_from_after(["a", "b", "a"])])
try_("after []", lambda: start_edges_from_after([]))
try_("after 'ab' (string)", lambda: [str(e) for e in start_edges_from_after("ab")])
print("str:", str(E(S("v", "success"), S("a"))), "|", str(E()))

print("== NodeSpec")
try_("default instance id", lambda: N("x").instance_id)
try_("instance_id ''", lambda: NodeSpec(id="x", type="t", instance_id="").instance_id)
try_("explicit instance", lambda: NodeSpec(id="x", type="t", instance_id="x@v5").instance_id)
try_("bad id 'a.b'", lambda: N("a.b"))
try_("empty type", lambda: NodeSpec(id="x", type=""))
try_("params frozen", lambda: N("x", params={"a": [1]}).params["a"].append(2))
try_("make_instance_id", lambda: make_instance_id("x", 3))
try_("Graph version -1", lambda: Graph(version=-1))

print("== queries")
g = Graph(nodes=(N("a"), N("b", "mid", E(S("a", "success"))), N("c", "mid", E(S("a"), S("b")), E(S("zz"))), N("a", "sink")),
          subscriptions=(sub("a.out", "b.inp"), sub("b.out", "c.inp"), sub("c.out", "b.inp"), sub("a.out", "c.aux")))
print("node('a').type (dup id, first wins):", g.node("a").type)
print("source_of b.inp (two subs, first returned):", g.source_of("b", "inp"))
print("consumers_of a.out:", [f"{s.target_node}.{s.target_port}" for s in g.consumers_of("a", "out")])
print("upstream b:", g.upstream("b"), "downstream b:", g.downstream("b"))
print("start_edges_of zz:", g.start_edges_of("zz"))
print("start_dependencies c:", g.start_dependencies("c"), "dependents a:", g.start_dependents("a"))
print("roots:", g.node_ids_without_start_dependencies())
g_empty_edge = Graph(nodes=(N("r", "src", E()),))
print("node with empty StartEdge root?:", g_empty_edge.node_ids_without_start_dependencies())
print("closure down a:", g.downstream_closure(["a", "nope"]))
print("closure up c (subs only):", g.upstream_closure(["c"], include_start_edges=False))
print("closure up c (with start edges):", g.upstream_closure(["c"]))
print("affected_by b:", g.affected_by("b"))
print("affected_by b port inp:", g.affected_by("b", "inp"))
print("affected_by sink reads:", Graph(nodes=(N("s", "sink"),)).affected_by("s", reads_by_type={"sink": ("camera_file",)}))
print("affected_by reads_by_type={} ->", Graph(nodes=(N("s", "sink"),)).affected_by("s", reads_by_type={}).reads)
print("external_reads all:", g.external_reads({"mid": ("f",)}))
print("is_current:", g.is_current("b", "b@v0"), g.is_current("b", "b@v1"), g.is_current("zz", "zz@v0"))

print("== cycles")
cg = Graph(nodes=(N("x", "src", E(S("x"))),))
print("self loop:", cg.start_edge_cycles())
cg2 = Graph(nodes=(N("a", "src", E(S("b"))), N("b", "src", E(S("a")), E(S("c"))), N("c", "src", E(S("b"))), N("d", "src", E(S("a"))), N("e")))
print("two loops sharing b + d behind:", cg2.start_edge_cycles())
cg3 = Graph(nodes=(N("p", "src"), N("q", "src", E(S("p")), E(S("q")))))
print("self-wait on second edge:", cg3.start_edge_cycles())
cg4 = Graph(nodes=(N("p", "src", E(S("ghost"))),))
print("unknown source only:", cg4.start_edge_cycles())

